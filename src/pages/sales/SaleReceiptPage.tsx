import { useEffect, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { salesApi } from '../../api'
import AppShell from '../../components/AppShell'
import { Alert, LoadingState } from '../../components/PageState'
import StatusPill from '../../components/StatusPill'
import { formatDate, money, prettyLabel } from '../../lib/format'
import { getErrorMessage } from '../../lib/http'
import type { SaleReceipt } from '../../types'

export default function SaleReceiptPage() {
  const { id } = useParams()
  const [receipt, setReceipt] = useState<SaleReceipt | null>(null)
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    if (!id) return
    const load = async () => {
      try {
        setReceipt(await salesApi.receipt(id))
      } catch (err) {
        setError(getErrorMessage(err))
      } finally {
        setLoading(false)
      }
    }
    void load()
  }, [id])

  return (
    <AppShell
      pageTitle="Sale receipt"
      pageSubtitle="Printable receipt generated by the API."
      action={
        <div className="action-row">
          <button type="button" className="primary-button" onClick={() => window.print()}>Print</button>
          <Link to="/sales" className="secondary-button">Back to sales</Link>
        </div>
      }
    >
      {error && <Alert>{error}</Alert>}
      {loading || !receipt ? <LoadingState /> : (
        <section className="panel module-panel receipt-panel">
          <div className="receipt-box">
            <div className="receipt-header">
              <strong>CAVAKUZ</strong>
              <small>{receipt.receipt_number}</small>
            </div>
            <div className="receipt-line">
              <span>Customer</span>
              <strong>{receipt.customer?.name ?? '—'}</strong>
            </div>
            <div className="receipt-line">
              <span>Date</span>
              <strong>{formatDate(receipt.transaction_date)}</strong>
            </div>
            <div className="receipt-line">
              <span>Payment</span>
              <strong>{prettyLabel(receipt.payment_method)}</strong>
            </div>
            {(receipt.items ?? []).map((item) => (
              <div className="receipt-line" key={item.id}>
                <span>{item.inventory?.name ?? `Item #${item.inventory_id}`} × {item.quantity}</span>
                <strong>{money(item.total_price)}</strong>
              </div>
            ))}
            <div className="receipt-line total">
              <span>Total</span>
              <strong>{money(receipt.total_amount)}</strong>
            </div>
            <div className="receipt-line status-line">
              <span>Status</span>
              <StatusPill value={receipt.payment_status} />
            </div>
          </div>
        </section>
      )}
    </AppShell>
  )
}
